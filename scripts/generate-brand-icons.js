// Regenerates src/brand/brand-icons.js from the icon files in src/public.
// The icons are embedded as data so the logo is served on serverless platforms
// (Vercel) where static files outside the function bundle may not be shipped.
//
//   npm run icons         (or: node scripts/generate-brand-icons.js)

const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const PUBLIC_DIR = path.join(ROOT, 'src', 'public');
const OUT_FILE = path.join(ROOT, 'src', 'brand', 'brand-icons.js');

function chunkBase64(buf, width = 100) {
  const b64 = buf.toString('base64');
  const lines = [];
  for (let i = 0; i < b64.length; i += width) lines.push(b64.slice(i, i + width));
  // Each chunk is its own quoted string joined with +, so nothing leaks into the data.
  return lines.map((line) => `  '${line}'`).join(' +\n');
}

const ico = fs.readFileSync(path.join(PUBLIC_DIR, 'favicon.ico'));
const png = fs.readFileSync(path.join(PUBLIC_DIR, 'apple-touch-icon.png'));
const svg = fs.readFileSync(path.join(PUBLIC_DIR, 'favicon.svg'), 'utf8').trim();

const out = `// Brand icons embedded as data so the school logo is served on every platform,
// including serverless builds where static files outside the bundle are not shipped.
//
// Generated by scripts/generate-brand-icons.js - do not edit by hand.
// Source artwork: src/public/img/logo.svg (royal-blue rounded square, white graduation cap).

const FAVICON_ICO_BASE64 =
${chunkBase64(ico)};

const APPLE_TOUCH_ICON_BASE64 =
${chunkBase64(png)};

const FAVICON_SVG = ${JSON.stringify(svg)};

module.exports = {
  faviconIco: Buffer.from(FAVICON_ICO_BASE64, 'base64'),
  appleTouchIcon: Buffer.from(APPLE_TOUCH_ICON_BASE64, 'base64'),
  faviconSvg: FAVICON_SVG,
};
`;

fs.mkdirSync(path.dirname(OUT_FILE), { recursive: true });
fs.writeFileSync(OUT_FILE, out);

// Fail loudly if the round trip is not byte-exact.
const written = require(OUT_FILE);
if (Buffer.compare(written.faviconIco, ico) !== 0) throw new Error('favicon.ico round trip failed');
if (Buffer.compare(written.appleTouchIcon, png) !== 0) throw new Error('apple-touch-icon round trip failed');
if (written.faviconSvg !== svg) throw new Error('favicon.svg round trip failed');

console.log(
  `brand-icons.js written (${(out.length / 1024).toFixed(1)} KB) - ico ${ico.length}b, png ${png.length}b, svg ${svg.length}b - byte-exact`
);
